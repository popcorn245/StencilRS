// Type declarations for a component library: the `components.d.ts` that `stencil build` writes
// (its `types` output), generated from `analyze()`'s metadata. Pure JavaScript, no TypeScript.
//
//   import { generateTypes } from '@popcorn245/stencilrs';
//   const { code } = generateTypes([{ file: 'src/corn-probe.tsx', source }], { outFile: 'dist/components.d.ts' });
//
// The Vite plugin runs it for a library build with `stencilrs({ dts: true })`.
import { dirname, isAbsolute, posix, relative, resolve, sep } from 'node:path';

import { analyze } from './index.js';

const HEADER = `/* eslint-disable */
/**
 * This is an autogenerated file created by stencilrs.
 * It contains typing information for all components that exist in this project.
 */`;

// Names a generated declaration or an import must not take.
const RESERVED = new Set(['Components', 'LocalJSX', 'JSX', 'JSXBase', 'HTMLStencilElement', 'HTMLElementTagNameMap', 'IntrinsicElements']);

// Types a consumer's TypeScript always has (lib.es / lib.dom): a reference to one needs no import.
const LIB_GLOBALS = new Set(
  (
    'Promise Array ReadonlyArray Record Partial Required Readonly Pick Omit Exclude Extract NonNullable ReturnType Parameters ' +
    'ConstructorParameters InstanceType Awaited Uppercase Lowercase Capitalize Uncapitalize ThisType Map Set WeakMap WeakSet ' +
    'ReadonlyMap ReadonlySet Date RegExp Error Function Object String Number Boolean Symbol BigInt Iterable Iterator ' +
    'IterableIterator AsyncIterable AsyncIterator ArrayBuffer SharedArrayBuffer DataView Int8Array Uint8Array Uint8ClampedArray ' +
    'Int16Array Uint16Array Int32Array Uint32Array Float32Array Float64Array BigInt64Array BigUint64Array JSON Math ' +
    'Element Node Document Window Event CustomEvent EventTarget DocumentFragment ShadowRoot Text Range Selection NodeList ' +
    'HTMLCollection DOMRect DOMRectReadOnly DOMTokenList DOMStringMap CSSStyleDeclaration CSSStyleSheet File FileList Blob ' +
    'FormData Headers Request Response URL URLSearchParams AbortSignal AbortController ReadableStream WritableStream ' +
    'MediaStream MediaStreamTrack ImageData ImageBitmap Image Audio Worker MessagePort ErrorEvent ' +
    'ElementInternals ValidityState CSSNumericValue IntersectionObserver ResizeObserver MutationObserver ' +
    'EventListener EventListenerOrEventListenerObject AddEventListenerOptions ScrollIntoViewOptions FocusOptions ' +
    'PropertyKey TemplateStringsArray Intl'
  ).split(' '),
);
const LIB_GLOBAL_PATTERNS = [/^(HTML|SVG|MathML)\w*Element$/, /^\w*Event$/, /^\w+EventMap$/];
const isLibGlobal = (name) => LIB_GLOBALS.has(name) || LIB_GLOBAL_PATTERNS.some((re) => re.test(name));

const q = (s) => JSON.stringify(s);

/** `/** ... *\/` for Stencil's `{ text, tags }` docs, or '' when there are none. */
function jsdoc(docs, indent, defaultValue) {
  const lines = [];
  if (docs?.text) lines.push(...docs.text.replaceAll('*/', '*\\/').split(/\r?\n/));
  for (const tag of docs?.tags ?? []) {
    const text = (tag.text ?? '').replaceAll('*/', '*\\/').split(/\r?\n/);
    lines.push(`@${tag.name}${text[0] ? ' ' + text[0] : ''}`, ...text.slice(1));
  }
  if (defaultValue !== undefined) lines.push(`@default ${defaultValue.replaceAll('*/', '*\\/')}`);
  if (!lines.length) return '';
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

/** What a module's own `import` statements bind: local name -> `{ spec, kind, imported }`. */
function scanImports(source) {
  const out = new Map();
  const stmt = /\bimport\s+(?:type\s+)?([^'";]*?)\s*from\s*(['"])([^'"]+)\2/g;
  for (const [, clause, , spec] of source.matchAll(stmt)) {
    const named = /\{([^}]*)\}/.exec(clause);
    const rest = clause.replace(/\{[^}]*\}/, '');
    const ns = /\*\s*as\s+([\w$]+)/.exec(rest);
    if (ns) out.set(ns[1], { spec, kind: 'namespace', imported: '*' });
    else {
      const def = /^\s*([\w$]+)\s*,?\s*$/.exec(rest);
      if (def) out.set(def[1], { spec, kind: 'default', imported: 'default' });
    }
    for (const part of named?.[1].split(',') ?? []) {
      const m = /^\s*(?:type\s+)?([\w$]+)(?:\s+as\s+([\w$]+))?\s*$/.exec(part);
      if (m) out.set(m[2] ?? m[1], { spec, kind: 'named', imported: m[1] });
    }
  }
  return out;
}

const TYPE_KEYWORDS = new Set(
  'string number boolean any unknown never void null undefined object symbol bigint true false typeof keyof readonly unique infer extends is as new this in of function asserts'.split(' '),
);

/** The identifiers a type text uses as type names: not keywords, property keys, parameter names or members of a path. */
function typeNames(text) {
  const bare = text.replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`/g, '""');
  const names = new Set();
  for (const m of bare.matchAll(/(?<![.\w$])([A-Za-z_$][\w$]*)(?![\w$])(?!\s*\??\s*:)/g)) {
    if (!TYPE_KEYWORDS.has(m[1])) names.add(m[1]);
  }
  return names;
}

const declaresType = (source, name) => new RegExp(`\\b(?:type|interface|enum|class)\\s+${name}\\b`).test(source);

const exportsName = (source, name) =>
  new RegExp(`\\bexport\\s+(?:declare\\s+)?(?:abstract\\s+)?(?:const\\s+)?(?:type|interface|enum|class)\\s+${name}\\b`).test(source) ||
  new RegExp(`\\bexport\\s*(?:type\\s*)?\\{[^}]*\\b${name}\\b[^}]*\\}(?!\\s*from)`).test(source);

/** Replace identifiers `from` -> `to` outside string literals and property positions. */
function renameIdent(text, from, to) {
  const re = new RegExp(`(?<![.\\w$])${from.replaceAll('$', '\\$')}(?![\\w$])(?!\\s*\\??\\s*:)`, 'g');
  return text
    .split(/("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(re, to)))
    .join('');
}

/** Import bookkeeping shared by every component of one declaration file. */
function createImports(outDir) {
  const used = new Set(RESERVED);
  // `${spec}\0${kind}\0${imported}` -> local name
  const bound = new Map();
  const entries = [];
  const bind = (spec, kind, imported, wanted) => {
    const key = `${spec}\0${kind}\0${imported}`;
    if (bound.has(key)) return bound.get(key);
    let local = wanted;
    for (let n = 1; used.has(local); n++) local = `${wanted}${n}`;
    used.add(local);
    bound.set(key, local);
    entries.push({ spec, kind, imported, local });
    return local;
  };
  const claim = (name) => used.add(name);
  const render = () => {
    const bySpec = new Map();
    for (const e of entries) bySpec.set(e.spec, [...(bySpec.get(e.spec) ?? []), e]);
    const lines = [];
    for (const [spec, list] of bySpec) {
      const named = list.filter((e) => e.kind === 'named');
      for (const e of list.filter((e) => e.kind !== 'named')) {
        lines.push(e.kind === 'namespace' ? `import type * as ${e.local} from ${q(spec)};` : `import type ${e.local} from ${q(spec)};`);
      }
      if (named.length) {
        lines.push(`import type { ${named.map((e) => (e.imported === e.local ? e.local : `${e.imported} as ${e.local}`)).join(', ')} } from ${q(spec)};`);
        lines.push(`export type { ${named.map((e) => (e.imported === e.local ? e.local : `${e.imported} as ${e.local}`)).join(', ')} } from ${q(spec)};`);
      }
    }
    return lines;
  };
  /** A module specifier as written in `file`, as seen from the declaration file. */
  const specFrom = (file, spec) => {
    if (!spec.startsWith('.')) return spec;
    const target = resolve(dirname(file), spec);
    const rel = relative(outDir, target).split(sep).join('/');
    return rel.startsWith('.') ? rel : `./${rel}`;
  };
  return { bind, claim, render, specFrom };
}

/**
 * Generate the declaration text for components.
 *
 * Each module is `{ file, source, components? }`: `components` are the `analyze()` result for it
 * (the Vite plugin passes what it already computed); left out, `analyze` is run with
 * `resolveImports: true`. Types a prop, event or method mentions are imported from where the
 * component got them (a relative specifier is rewritten relative to `outFile`; packages stay
 * as written), or from the component file itself for a type declared there (it must be
 * exported). A type that cannot be resolved becomes `any` with a comment saying which.
 *
 * @param {{ file: string, source: string, components?: object[] }[]} modules
 * @param {{ outFile?: string }} [options] outFile: where the text will be written (default
 *   `components.d.ts` in the working directory), which relative imports are computed from
 * @returns {{ code: string, components: string[], diagnostics: { file: string, message: string }[] }}
 */
export function generateTypes(modules, options = {}) {
  const outFile = resolve(options.outFile ?? 'components.d.ts');
  const imports = createImports(dirname(outFile));
  const diagnostics = [];
  const items = [];
  for (const mod of modules) {
    const file = isAbsolute(mod.file) ? mod.file : resolve(mod.file);
    let components = mod.components;
    if (!components) {
      // `complexTypes` for method signatures; its "not ported" errors only mean a member has no `resolved`.
      const result = analyze(mod.source, file, { resolveImports: true, complexTypes: true });
      for (const d of result.diagnostics.filter((d) => !d.message.startsWith('stencilrs:'))) diagnostics.push({ file, message: d.message });
      components = result.components;
    }
    const scanned = scanImports(mod.source);
    for (const component of components) items.push({ file, source: mod.source, scanned, component });
  }
  items.sort((a, b) => (a.component.tagName < b.component.tagName ? -1 : a.component.tagName > b.component.tagName ? 1 : 0));
  const seen = new Set();
  const unique = items.filter((i) => !seen.has(i.component.tagName) && seen.add(i.component.tagName));
  for (const i of unique) imports.claim(`HTML${i.component.componentClassName}Element`);

  /**
   * `text` with every type it names reachable from the declaration file, or null when one is not
   * (the first such name goes to `missing`). The names are read off the text itself and matched to
   * the module's own `import`s and exported declarations, so a type the analyzer could not
   * resolve (`complexTypes` errors) is handled the same as one it could.
   */
  const resolveType = (item, text, missing) => {
    let out = text;
    for (const name of typeNames(text)) {
      const scan = item.scanned.get(name);
      let bound = null;
      if (scan) {
        bound = imports.bind(imports.specFrom(item.file, scan.spec), scan.kind, scan.imported, name);
      } else if (declaresType(item.source, name)) {
        if (!exportsName(item.source, name)) {
          missing.push(`${name} (declared in ${item.file} but not exported)`);
          return null;
        }
        const spec = imports.specFrom(item.file, './' + posix.basename(item.file).replace(/\.[cm]?[jt]sx?$/, ''));
        bound = imports.bind(spec, 'named', name, name);
      } else if (!isLibGlobal(name)) {
        missing.push(name);
        return null;
      }
      if (bound && bound !== name) out = renameIdent(out, name, bound);
    }
    return out;
  };
  const typeOrAny = (item, text, label) => {
    const missing = [];
    const t = resolveType(item, text || 'any', missing);
    if (t !== null) return t;
    diagnostics.push({ file: item.file, message: `${label}: type \`${text}\` uses ${missing[0]}, which cannot be imported; emitted as any` });
    return `any /* unresolved: ${text.replaceAll('*/', '*\\/')} */`;
  };

  const components = [];
  const customEvents = [];
  const globals = [];
  const jsx = [];
  const augment = [];
  const tagMap = [];
  const intrinsic = [];

  for (const item of unique) {
    const c = item.component;
    const cls = c.componentClassName;
    const el = `HTML${cls}Element`;
    const where = `<${c.tagName}>`;

    const props = c.properties.map((p) => {
      const t = typeOrAny(item, p.complexTypeOriginal || p.complexType?.original, `${where} @Prop ${p.name}`);
      return { p, t };
    });
    const methods = c.methods.map((m) => {
      const missing = [];
      let sig = resolveType(item, m.complexType?.signature || '(...args: any[]) => Promise<any>', missing);
      if (sig === null) {
        diagnostics.push({ file: item.file, message: `${where} @Method ${m.name}: signature uses ${missing[0]}, which cannot be imported; emitted as any` });
        sig = '(...args: any[]) => Promise<any>';
      }
      return { m, sig };
    });
    const events = c.events.map((e) => ({
      e,
      t: typeOrAny(item, e.complexType?.original, `${where} @Event ${e.name}`),
    }));

    // Components.<Cls>
    let body = '';
    for (const { p, t } of props) {
      body += jsdoc(p.docs, '        ', p.defaultValue) + `        ${q(p.name)}${p.optional && !p.required ? '?' : ''}: ${t};\n`;
    }
    for (const { m, sig } of methods) body += jsdoc(m.docs, '        ') + `        ${q(m.name)}: ${sig};\n`;
    components.push(jsdoc(c.docs, '    ') + `    interface ${cls} {\n${body}    }`);

    // HTML<Cls>Element
    const hasEvents = events.length > 0;
    let extra = '';
    let eventMap = '';
    if (hasEvents) {
      customEvents.push(
        `export interface ${cls}CustomEvent<T> extends CustomEvent<T> {\n    detail: T;\n    target: ${el};\n}`,
      );
      eventMap = `    interface ${el}EventMap {\n${events.map(({ e, t }) => `        ${q(e.name)}: ${t};`).join('\n')}\n    }\n`;
      const overloads = (verb, opts) =>
        [
          `        ${verb}EventListener<K extends keyof ${el}EventMap>(type: K, listener: (this: ${el}, ev: ${cls}CustomEvent<${el}EventMap[K]>) => any, options?: boolean | ${opts}): void;`,
          `        ${verb}EventListener<K extends keyof DocumentEventMap>(type: K, listener: (this: Document, ev: DocumentEventMap[K]) => any, options?: boolean | ${opts}): void;`,
          `        ${verb}EventListener<K extends keyof HTMLElementEventMap>(type: K, listener: (this: HTMLElement, ev: HTMLElementEventMap[K]) => any, options?: boolean | ${opts}): void;`,
          `        ${verb}EventListener(type: string, listener: EventListenerOrEventListenerObject, options?: boolean | ${opts}): void;`,
        ].join('\n');
      extra = `\n${overloads('add', 'AddEventListenerOptions')}\n${overloads('remove', 'EventListenerOptions')}\n    `;
    }
    globals.push(
      eventMap +
        jsdoc(c.docs, '    ') +
        `    interface ${el} extends Components.${cls}, HTMLStencilElement {${extra}}\n` +
        `    var ${el}: {\n        prototype: ${el};\n        new (): ${el};\n    };`,
    );
    tagMap.push(`        ${q(c.tagName)}: ${el};`);

    // LocalJSX.<Cls>
    let jsxBody = '';
    for (const { p, t } of props) jsxBody += jsdoc(p.docs, '        ', p.defaultValue) + `        ${q(p.name)}${p.required ? '' : '?'}: ${t};\n`;
    for (const { e, t } of events) {
      const handler = `on${e.name.charAt(0).toUpperCase()}${e.name.slice(1)}`;
      jsxBody += jsdoc(e.docs, '        ') + `        ${q(handler)}?: (event: ${cls}CustomEvent<${t}>) => void;\n`;
    }
    jsx.push(jsdoc(c.docs, '    ') + `    interface ${cls} {\n${jsxBody}    }`);
    intrinsic.push(`        ${q(c.tagName)}: ${cls};`);
    augment.push(`            ${q(c.tagName)}: LocalJSX.IntrinsicElements[${q(c.tagName)}] & JSXBase.HTMLAttributes<${el}>;`);
  }

  const importLines = imports.render();
  const code = [
    HEADER,
    'import { HTMLStencilElement, JSXBase } from "@stencil/core/runtime";',
    ...importLines,
    `export namespace Components {\n${components.join('\n')}\n}`,
    ...customEvents,
    `declare global {\n${globals.join('\n')}\n    interface HTMLElementTagNameMap {\n${tagMap.join('\n')}\n    }\n}`,
    `declare namespace LocalJSX {\n${jsx.join('\n')}\n    interface IntrinsicElements {\n${intrinsic.join('\n')}\n    }\n}`,
    'export { LocalJSX as JSX };',
    `declare module "@stencil/core" {\n    export namespace JSX {\n        interface IntrinsicElements {\n${augment.join('\n')}\n        }\n    }\n}`,
  ].join('\n');
  return { code: code + '\n', components: unique.map((i) => i.component.tagName), diagnostics };
}
