// Generates dom-events.generated.js: the `on*` names of happy-dom's window and HTMLElement, which the
// server renderer needs without a DOM (EventPart's `onclick in globalThis`, and "does the page
// delegate this event or must the component hydrate on load").  node spike/gen-dom-events.mjs
import { Window } from 'happy-dom';
import { writeFileSync } from 'node:fs';
const w = new Window();
const names = (o) => {
  const s = new Set();
  for (let p = o; p && p !== Object.prototype; p = Object.getPrototypeOf(p)) for (const k of Object.getOwnPropertyNames(p)) if (k.startsWith('on')) s.add(k);
  return [...s].sort();
};
writeFileSync(
  new URL('./dom-events.generated.js', import.meta.url),
  `// Generated by spike/gen-dom-events.mjs from happy-dom: the \`on*\` names the server renderer asks about.\nexport const WINDOW_ON = new Set(${JSON.stringify(names(w))});\nexport const ELEMENT_ON = new Set(${JSON.stringify(names(w.HTMLElement.prototype))});\n`,
);
